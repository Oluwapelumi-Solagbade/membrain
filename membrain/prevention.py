ALWAYS = (
    "Keep your mind active: reading, Quran memorisation, learning a skill, or games with grandchildren all count.",
    "حافظ على نشاط عقلك: القراءة، حفظ القرآن، تعلّم مهارة جديدة، أو اللعب مع الأحفاد.",
)

MODIFIABLE_FACTORS = ["hypertension", "diabetes", "ldl", "physical_inactivity", "smoking", "obesity",
                      "hearing_loss", "vision_loss", "depression", "social_isolation", "alcohol",
                      "tbi", "low_education", "air_pollution"]


def prevention_plan(context: dict, lang: str = "en") -> dict:
    items = []
    for rid, test, evidence, en, ar in RULES:
        try:
            hit = bool(test(context))
        except Exception:
            hit = False
        if hit:
            items.append({"rule": rid, "text": ar if lang == "ar" else en, "evidence": evidence})
    items.append({"rule": "cognitive_engagement", "text": ALWAYS[1] if lang == "ar" else ALWAYS[0],
                  "evidence": "Lancet Commission 2024 (education / cognitive activity)"})
    return {"version": PREVENTION_VERSION, "items": items[:5], "all_matched": [i["rule"] for i in items]}


def risk_context(context: dict) -> dict:
    """Integrated, consent-scoped risk context for the clinician dossier.

    No probability is computed: factors are listed with source and value.
    Genomic data (e.g. APOE) is only shown to clinicians and never disclosed
    to the participant without counselling.
    """
    present = []
    m = {
        "hypertension": (context.get("sbp") or 0) >= 140 or context.get("hypertension"),
        "diabetes": (context.get("hba1c") or 0) >= 6.5 or context.get("diabetes"),
        "ldl": (context.get("ldl") or 0) >= 3.0,
        "physical_inactivity": (context.get("activity_min_week") if context.get("activity_min_week") is not None else 999) < 150,
        "smoking": context.get("smoker"),
        "obesity": (context.get("bmi") or 0) >= 30,
        "hearing_loss": context.get("hearing_difficulty"),
        "vision_loss": context.get("vision_difficulty"),
        "depression": context.get("mood_positive"),
        "social_isolation": context.get("social_isolation"),
        "low_education": context.get("education") in ("none", "primary"),
    }
    for k, v in m.items():
        if v:
            present.append(k)
    return {"modifiable_factors_present": present, "count": len(present), "of": len(MODIFIABLE_FACTORS),
            "family_history_dementia": context.get("family_history_dementia"),
            "genomic": {"apoe4": context.get("apoe4"), "disclosure": "clinician-mediated with counselling only"}
            if context.get("consent_genomic") else None,
            "reversible_cause_checks": ["TSH", "Vitamin B12", "Folate", "Full blood count", "HbA1c", "Renal function",
                                        "Medication review (anticholinergic burden)", "Depression (PHQ-9)",
                                        "Sleep apnoea screen (STOP-BANG)", "Hearing and vision"]}


