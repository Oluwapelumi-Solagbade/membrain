def participant_message(ev: dict, lang: str = "en") -> dict:
    i = 1 if lang == "ar" else 0
    key = "INVALID" if not ev.get("valid", True) else ev["level"]
    out = {"key": key, "text": MESSAGES[key][i]}
    if any(c["code"] == "mood" for c in ev.get("confounders", [])):
        out["support"] = MESSAGES["MOOD_SUPPORT"][i]
    return out
