// Copies MemBrain's engine, intake extractor and synthetic data from ../web into lib/generated/.
// ../web stays the single source of truth: web/parity_test.js checks those files against the Python
// engine, and this site runs byte-identical copies of them. Run by `npm run dev` and `npm run build`.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, "..", "..", "web");
const out = join(here, "..", "lib", "generated");
mkdirSync(out, { recursive: true });

// 1. The data the Python pipeline exports (window.MB_DATA), split so each page loads only what it needs.
const sandbox = { window: {} };
vm.runInNewContext(readFileSync(join(web, "data.js"), "utf8"), sandbox);
const D = sandbox.window.MB_DATA;
const write = (name, value) => writeFileSync(join(out, name), JSON.stringify(value));
const withoutBulk = (p) => {
  const copy = { ...p };
  delete copy.fhir_example; // large; the case page builds FHIR on demand
  return copy;
};
write("engine-data.json", { config: D.config, items: D.items });
write("intake-data.json", D.intake);
write("personas.json", D.personas.map(withoutBulk));
// The navigator config without the 160-referral synthetic log (its summary metrics are kept).
const { synthetic_log: _log, ...navigator } = D.navigator;
void _log;
write("navigator.json", navigator);
write("programme-data.json", { validation: D.validation, navai: D.navai, prevention_rules: D.prevention_rules, messages: D.messages });

// 2. The engines, wrapped as ES modules. The source is untouched between the wrapper lines.
const wrap = (file, name) => {
  const src = readFileSync(join(web, file), "utf8");
  writeFileSync(
    join(out, file.replace(/\.js$/, ".mjs")),
    `// Generated from web/${file} by scripts/sync-data.mjs. Do not edit; edit web/${file}.\n` +
      `const module = { exports: {} };\n${src}\nexport default /** @type {any} */ (module.exports);\nexport const ${name} = module.exports;\n`,
  );
  // Loose types here; lib/mb.ts types the parts the site uses.
  writeFileSync(
    join(out, file.replace(/\.js$/, ".d.mts")),
    `// Generated by scripts/sync-data.mjs.\ndeclare const ${name}: (data: unknown) => any;\nexport default ${name};\nexport { ${name} };\n`,
  );
};
wrap("engine.js", "makeEngine");
wrap("intake.js", "makeIntake");
wrap("navigator.js", "makeNavigator");

console.log(`sync-data: ${D.personas.length} personas, engine ${D.config.ENGINE_VERSION}, intake ${D.intake.INTAKE_VERSION}`);
